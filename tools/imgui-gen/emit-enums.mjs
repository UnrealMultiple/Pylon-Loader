/**
 * Emit enum gen files mirroring ImGui.NET (ImGuiWindowFlags.gen.cs etc.).
 * Members: strip enum-name prefix, adjust names (ImGuiKey special cases),
 * [Flags] when name contains "Flags".
 */
import { writeFileSync, mkdirSync } from 'fs';

// C#-reserved words that need '@' prefix (ImGui.NET uses these rules)
const RESERVED = new Set(['base','event','fixed','in','interface','lock','null','object','params','ref','return','string','this','throw','type','typeof','uint','ulong','unchecked','unsafe','ushort','using','var','void','volatile','while','out','params','readonly','as','abstract','bool','byte','char','class','const','decimal','delegate','do','double','else','enum','explicit','extern','false','finally','float','for','foreach','goto','if','implicit','int','is','namespace','new','operator','private','protected','public','sealed','static','switch','try','true','base','checked']);

export function emitEnums(model, outDir) {
  mkdirSync(outDir, { recursive: true });
  let n = 0;
  // exclude internal/internal-only enums; focus on public ImGui surface enums
  const PUBLIC_ENUMS = null; // generate all parsed enums
  for (const [name, e] of Object.entries(model.enums)) {
    if (!model.src || model.src['enum:' + name] === undefined) continue; // skip synthetic
    const csName = name.endsWith('_') ? name.slice(0, -1) : name;
    const flags = csName.includes('Flags');
    const L = [];
    L.push('// <auto-generated>');
    L.push('namespace Pylon.ImGui');
    L.push('{');
    if (flags) L.push('    [System.Flags]');
    L.push('    public enum ' + csName);
    L.push('    {');
    const seenNames = new Set();
    for (const m of e.members) {
      let memName = m.name;
      // strip the longest known prefix
      for (const pre of [name + '_', 'ImGui' + csName.replace(/^ImGui/, '') + '_', 'ImGuiKey_', 'ImGuiMod_', 'ImGuiCol_', 'ImGuiStyleVar_', 'ImDrawFlags_', 'ImDrawListFlags_']) {
        if (memName.startsWith(pre)) { memName = memName.slice(pre.length); break; }
      }
      // ImGuiKey member names: e.g. ImGuiKey_LeftArrow -> LeftArrow; digit keys? _0.._9 -> _0
      if (csName === 'ImGuiKey') {
        if (/^ImGuiKey_/.test(m.name)) memName = m.name.slice('ImGuiKey_'.length);
        else if (/^ImGuiMod_/.test(m.name)) memName = 'Mod' + m.name.slice('ImGuiMod_'.length);
      }
      if (csName === 'ImGuiMouseButton') {
        if (/^ImGuiMouseButton_/.test(m.name)) memName = m.name.slice('ImGuiMouseButton_'.length);
      }
      if (/^[0-9]/.test(memName)) memName = '_' + memName;
      if (RESERVED.has(memName)) memName = '@' + memName;
      if (memName.includes('-')) memName = memName.replace(/-/g, '_');
      if (seenNames.has(memName)) continue;
      seenNames.add(memName);
      L.push('        ' + memName + ' = ' + m.value + ',');
    }
    L.push('    }');
    L.push('}');
    writeFileSync(outDir + csName + '.gen.cs', L.join('\n'), 'utf8');
    n++;
  }
  return n;
}

export default { emitEnums };
