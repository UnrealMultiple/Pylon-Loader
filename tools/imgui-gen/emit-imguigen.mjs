/**
 * Emit ImGui.gen.cs — friendly static ImGui class (ImGui.NET style marshalling).
 */
import { writeFileSync, mkdirSync } from 'fs';
import { normType, csType, PTR_WRAP } from './cs-types.mjs';

const KEYWORDS = new Set(['ref','object','event','base','params','lock','fixed','in','out','is','as','string','int','bool','float','uint','void','char','byte','short','long','double','decimal','new','return','this','null','true','false','if','else','for','foreach','while','do','switch','case','break','continue','goto','throw','try','catch','finally','default','delegate','enum','interface','namespace','operator','struct','class','const','static','public','private','protected','internal','readonly','override','virtual','sealed','abstract','using','var','async','await','where','when','yield','sizeof','typeof','stackalloc','nameof','global','partial','record']);
const UDT = { ImVec2: 'Vector2', ImVec4: 'Vector4', ImColor: 'ImColor' };
const CSTR = new Set(['char*']);
function isCstr(t) { const n = t.replace(/\s+/g, '').replace(/^const/, ''); return n === 'char*'; }

function pname(name, i) {
  if (name && !KEYWORDS.has(name) && !/^[0-9]/.test(name)) return name;
  return 'arg' + (i + 1);
}

export function emitImGuiGen(model, outDir) {
  mkdirSync(outDir, { recursive: true });
  const sep = outDir.endsWith('/') || outDir.endsWith('\\') ? outDir : outDir + '/';
  const L = [];
  const P = (s) => L.push(s);
  P('// <auto-generated>');
  P('using System;');
  P('using System.Numerics;');
  P('using System.Text;');
  P('');
  P('namespace Pylon.ImGui');
  P('{');
  P('    public static unsafe partial class ImGui');
  P('    {');
  const seen = new Set();
  for (const fn of model.functions) {
    if (fn.impl) continue;
    const exportName = fn.exportName || ('ig' + fn.name);
    if (seen.has(exportName)) continue;
    seen.add(exportName);
    emitFriendlyFn(fn, P);
  }
  P('    }');
  P('}');
  writeFileSync(sep + 'ImGui.gen.cs', L.join('\n'), 'utf8');
  return L.length;
}

function emitFriendlyFn(fn, P) {
  const params = (fn.params || []).filter(p => p.type.trim() && p.type.trim() !== '...');
  const rawRet = normType(fn.ret);
  const isUdt = !!UDT[rawRet];
  const isRefRet = rawRet.endsWith('&');
  const baseRet = rawRet.replace(/&+$/, '').trim();
  // friendly return type
  let retCs;
  if (isUdt) retCs = UDT[rawRet];
  else if (baseRet === 'void') retCs = 'void';
  else if (baseRet === 'bool') retCs = 'bool';
  else if (isCstr(baseRet)) retCs = 'string';
  else if (baseRet.endsWith('*')) retCs = PTR_WRAP[baseRet.slice(0,-1).trim()] || csType(rawRet);
  else if (isRefRet) retCs = PTR_WRAP[baseRet] || (csType(baseRet) + '*');
  else retCs = csType(rawRet);

  // signature params: friendly types
  const csDefault = (t, p) => {
    if (!p.hasDefault) return '';
    const e = (p.defaultExpr || '').trim();
    const ft = (() => {
      const tn = normType(p.type);
      if (tn === 'bool') return 'bool';
      if (isCstr(tn)) return 'string';
      if (tn.endsWith('*')) {
        const b = tn.slice(0, -1).trim();
        if (b === 'bool') return 'ref bool';
        if (PTR_WRAP[b]) return PTR_WRAP[b];
        if (['int','uint','float','double','byte','ushort','short','long','ulong'].includes(csType(b))) return 'ref ' + csType(b);
        return csType(tn);
      }
      return csType(tn);
    })();
    if (ft.startsWith('ref ') || (ft.endsWith('*') && !ft.endsWith('Ptr'))) return ''; // ref/raw-pointer params: no defaults
    if (!e) return '';
    let v;
    if (e === 'NULL') v = ft === 'string' ? 'null' : ((ft.endsWith('Ptr') || ft === 'IntPtr') ? 'default' : '0');
    else if (e === 'true' || e === 'false') v = e;
    else if (e === 'FLT_MAX') v = 'float.MaxValue';
    else if (e === 'sizeof(float)') v = '4';
    else if (/^"([^"]*)"$/.test(e)) v = e;
    else if (e.startsWith('ImVec2(') || e.startsWith('ImVec4(')) {
      v = 'default'; // Vector2/Vector4 default params must be compile-time constants in C#
    }
    else if (/^[-+0-9.eEfFuUlL]+$/.test(e)) v = ft === 'IntPtr' ? 'default' : (/^Im[A-Z]/.test(ft) ? '(' + ft + ')' + e : e);
    else v = null; // unsupported -> no default
    return v == null ? '' : ' = ' + v;
  };
  const sig = params.map((p, i) => {
    const t = normType(p.type);
    const name = pname(p.name, i);
    let ft;
    if (t === 'bool') ft = 'bool';
    else if (isCstr(t)) ft = 'string';
    else if (t === 'const char**' || t === 'char**') ft = 'string[]';
    else if (t.endsWith('*') && !t.endsWith('**')) {
      const base = t.slice(0, -1).trim();
      if (base === 'char') ft = 'string';
      else if (base === 'bool') ft = 'ref bool';
      else if (base === 'void') ft = 'IntPtr';
      else if (PTR_WRAP[base]) ft = PTR_WRAP[base];
      else if (['int','uint','float','double','byte','ushort','short','long','ulong'].includes(csType(base))) ft = 'ref ' + csType(base);
      else ft = csType(t); // struct ptr stays raw pointer (ImFontAtlas*)
    } else ft = csType(t);
    return ft + ' ' + name + csDefault(t, p);
  }).join(', ');
  const finalSig = (() => {
    const parts = sig.split(', ');
    const defaults = parts.map(s => s.includes(' = '));
    let dropFrom = -1;
    let firstOpt = -1;
    for (let k = 0; k < parts.length; k++) {
      if (defaults[k]) { if (firstOpt < 0) firstOpt = k; }
      else if (firstOpt >= 0) { dropFrom = firstOpt; break; }
    }
    if (dropFrom < 0) return sig;
    return parts.map((s, k) => (k >= dropFrom ? s.split(' =')[0] : s)).filter(Boolean).join(', ');
  })();
  P('        public static ' + retCs + ' ' + fn.name + '(' + finalSig + ')');
  P('        {');
  // marshalling prelude
  const callArgs = [];
  for (let i = 0; i < params.length; i++) {
    const p = params[i];
    const t = normType(p.type);
    const name = pname(p.name, i);
    if (t === 'bool') {
      P('            byte native_' + name + ' = ' + name + ' ? (byte)1 : (byte)0;');
      callArgs.push('native_' + name);
    } else if (isCstr(t)) {
      P('            byte* native_' + name + ';');
      P('            int ' + name + '_byteCount = 0;');
      P('            if (' + name + ' != null)');
      P('            {');
      P('                ' + name + '_byteCount = Encoding.UTF8.GetByteCount(' + name + ');');
      P('                if (' + name + '_byteCount > Util.StackAllocationSizeLimit)');
      P('                {');
      P('                    native_' + name + ' = Util.Allocate(' + name + '_byteCount + 1);');
      P('                }');
      P('                else');
      P('                {');
      P('                    byte* native_' + name + '_stackBytes = stackalloc byte[' + name + '_byteCount + 1];');
      P('                    native_' + name + ' = native_' + name + '_stackBytes;');
      P('                }');
      P('                int native_' + name + '_offset = Util.GetUtf8(' + name + ', native_' + name + ', ' + name + '_byteCount);');
      P('                native_' + name + '[native_' + name + '_offset] = 0;');
      P('            }');
      P('            else { native_' + name + ' = null; }');
      callArgs.push('native_' + name);
    } else if ((t === 'const char**' || t === 'char**') && !t.endsWith('***')) {
      P('            int* ' + name + '_byteCounts = stackalloc int[' + name + '.Length];');
      P('            int ' + name + '_byteCount = 0;');
      P('            for (int i = 0; i < ' + name + '.Length; i++)');
      P('            {');
      P('                string s = ' + name + '[i];');
      P('                ' + name + '_byteCounts[i] = Encoding.UTF8.GetByteCount(s);');
      P('                ' + name + '_byteCount += ' + name + '_byteCounts[i] + 1;');
      P('            }');
      P('            byte* native_' + name + '_data = stackalloc byte[' + name + '_byteCount];');
      P('            int offset = 0;');
      P('            for (int i = 0; i < ' + name + '.Length; i++)');
      P('            {');
      P('                string s = ' + name + '[i];');
      P('                offset += Util.GetUtf8(s, native_' + name + '_data + offset, ' + name + '_byteCounts[i]);');
      P('                native_' + name + '_data[offset++] = 0;');
      P('            }');
      P('            byte** native_' + name + ' = stackalloc byte*[' + name + '.Length];');
      P('            offset = 0;');
      P('            for (int i = 0; i < ' + name + '.Length; i++)');
      P('            {');
      P('                native_' + name + '[i] = &native_' + name + '_data[offset];');
      P('                offset += ' + name + '_byteCounts[i] + 1;');
      P('            }');
      callArgs.push('native_' + name);
    } else if (t.endsWith('*') && !t.endsWith('**')) {
      const base = t.slice(0, -1).trim();
      if (base === 'void') {
        callArgs.push(name + '.ToPointer()');
      } else if (PTR_WRAP[base]) {
        P('            ' + csType(base) + '* native_' + name + ' = ' + name + '.NativePtr;');
        callArgs.push('native_' + name);
      } else if (base === 'bool') {
        P('            byte native_' + name + '_val = ' + name + ' ? (byte)1 : (byte)0;');
        P('            byte* native_' + name + ' = &native_' + name + '_val;');
        callArgs.push('native_' + name);
      } else if (base === 'char') {
        callArgs.push(name); // string already handled above; unreachable
      } else if (PTR_WRAP[base] || ['int','uint','float','double','byte','ushort','short','long','ulong'].includes(csType(base))) {
        callArgs.push(name); // raw pointer passed through (caller provides ptr); ref handled below
      } else {
        callArgs.push(name);
      }
    } else {
      callArgs.push(name);
    }
  }
  // ref params (pointers to primitives): must pass real pointers -> fixed block
  const refParams = [];
  for (let i = 0; i < params.length; i++) {
    const p = params[i];
    const t = normType(p.type);
    const base = t.endsWith('*') && !t.endsWith('**') ? t.slice(0, -1).trim() : null;
    if (base && !isCstr(t) && base !== 'bool' && base !== 'char' && ['int','uint','float','double','byte','ushort','short','long','ulong'].includes(csType(base))) {
      const name = pname(p.name, i);
      refParams.push({ name, cs: csType(base) });
    }
  }
  const openFixed = refParams.length > 0;
  const retDeclType = (rawRet === 'bool') ? 'byte' : (isCstr(rawRet) ? 'byte*' : retCs);
  if (openFixed && !isUdt && retCs !== 'void') {
    P('            ' + retDeclType + ' ret' + (retDeclType === 'byte' ? ' = 0' : '') + ';');
  }
  if (openFixed) {
    for (const rp of refParams) P('            fixed (' + rp.cs + '* native_' + rp.name + ' = &' + rp.name + ')');
    P('            {');
    // replace callArgs entries for ref params
    for (let i = 0; i < params.length; i++) {
      const p = params[i];
      const t = normType(p.type);
      const base = t.endsWith('*') && !t.endsWith('**') ? t.slice(0, -1).trim() : null;
      if (base && !isCstr(p.type) && base !== 'bool' && base !== 'char' && ['int','uint','float','double','byte','ushort','short','long','ulong'].includes(csType(base))) {
        const name = pname(p.name, i);
        const ci = callArgs.indexOf(name);
        if (ci >= 0) callArgs[ci] = 'native_' + name;
      }
    }
  }
  const nativeCall = 'ImGuiNative.' + fn.exportName +
    (isUdt ? '(&__retval' + (callArgs.length ? ', ' + callArgs.join(', ') : '') + ')' : '(' + callArgs.join(', ') + ')');
  if (isUdt) {
    P('            ' + retCs + ' __retval;');
    P('            ' + nativeCall + ';');
  } else if (openFixed && retCs !== 'void') {
    P('            ret = ' + nativeCall + ';');
  } else {
    P('            ' + (retCs === 'void' ? nativeCall + ';' : (retDeclType + ' ret = ' + nativeCall + ';')));
  }
  // free string buffers
  for (let i = 0; i < params.length; i++) {
    const p = params[i];
    const t = normType(p.type);
    const name = pname(p.name, i);
    if (isCstr(t)) {
      P('            if (' + name + '_byteCount > Util.StackAllocationSizeLimit)');
      P('            {');
      P('                Util.Free(native_' + name + ');');
      P('            }');
    }
  }
  if (openFixed) P('            }');
  if (isUdt) P('            return __retval;');
  else if (retCs === 'void') { /* noop */ }
  else if (rawRet === 'bool') P('            return ret != 0;');
  else if (isCstr(baseRet)) P('            return Util.StringFromPtr(ret);');
  else P('            return ret;');
  P('        }');
  P('');
}

export default { emitImGuiGen };
