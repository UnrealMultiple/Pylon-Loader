/**
 * Emit per-struct gen files: raw layout struct + Ptr wrapper (ImGui.NET style).
 */
import { writeFileSync, mkdirSync } from 'fs';
import { normType, csType, csElem, PTR_WRAP } from './cs-types.mjs';

const LEGAL_FIXED = new Set(['byte','sbyte','short','ushort','int','uint','long','ulong','float','double']);

function joinSeg(seg) {
  const parts = [];
  for (const tk of seg) { if (tk.t === 'NEWLINE') continue; parts.push(tk.v); }
  let s = parts.join(' ');
  s = s.replace(/\s*<\s*/g, '<').replace(/>\s*/g, '> ')
       .replace(/\[\s*/g, '[').replace(/\s*\]/g, '] ')
       .replace(/(\w)(\*+)\s*/g, '$1$2 ')
       .replace(/&\s+/g, '& ')
       .replace(/::/g, '::')
       .replace(/\s+/g, ' ').trim();
  // bitfield suffix
  s = s.replace(/\s*:\s*\d+\s*$/, '');
  return s;
}

function resolveSize(expr, model) {
  expr = expr.trim();
  const n = parseInt(expr, 10);
  if (!Number.isNaN(n)) return n;
  for (const e of Object.values(model.enums)) {
    const mem = e.members.find(mm => mm.name === expr && typeof mm.value === 'number');
    if (mem) return mem.value;
  }
  return null;
}

export function emitStructGen(model, outDir) {
  mkdirSync(outDir, { recursive: true });
  const sep = outDir.endsWith('/') || outDir.endsWith('\\') ? outDir : outDir + '/';
  let n = 0;
  for (const s of Object.values(model.structs)) {
    const fields = [];
    for (const e of (s.entries || [])) {
      if (e.kind !== 'field') continue;
      const str = joinSeg(e.segments);
      if (!str || str.startsWith('IMGUI_API')) continue;
      for (const f of parseFields(str, s.name, model)) fields.push(f);
    }
    const methods = (s.methods || []).filter(m => m && m.name
      && m.name !== s.name
      && !m.name.startsWith('~')
      && m.name !== 'operator'
      && !normType(m.ret).startsWith('~')
      && !normType(m.ret).includes('(')
      && !normType(m.ret).includes('operator'));
    if (!fields.length && !methods.length) continue;
    const cs = emitOne(s.name, fields, methods, model);
    writeFileSync(sep + s.name + '.gen.cs', cs, 'utf8');
    n++;
  }
  return n;
}

// tolerate "unsigned short x, y;" -> two fields
function parseFields(str, structName, model) {
  // strip bitfield suffixes anywhere: 'unsigned int MetricsTotalSurface : 26'
  str = str.replace(/\s*:\s*\d+\s*$/g, '');
  str = str.replace(/(\w)\s*:\s*\d+/g, '$1');
  const out = [];
  // fn pointer field
  const fp = str.match(/^\(?\s*\*\s*(\w+)\s*\)/);
  if (fp) { out.push({ name: fp[1], type: 'void*', array: null, fnptr: true }); return out; }
  if (str.includes('(') && !str.includes('[')) {
    // maybe "Type (*Name)(...)" inline method pointer declarations
    const m2 = str.match(/(\w+)\s*\(\s*\*\s*(\w+)\s*\)\s*\(/);
    if (m2) { out.push({ name: m2[2], type: 'void*', array: null, fnptr: true }); return out; }
    return out;
  }
  // comma-separated declarators? "ImVec2 uv0, uv1;" or "unsigned short x, y;"
  const commaParts = str.split(',');
  let baseType = null;
  for (let i = 0; i < commaParts.length; i++) {
    const part = commaParts[i].trim();
    if (!part) continue;
    let m = part.match(/^(.*?)\s*(\w+)(\s*\[\s*([^\]]*)\s*\])?$/);
    let type, name, array = null;
    if (m) {
      type = normType(m[1]);
      name = m[2];
      if (m[4] && m[4].trim() !== '') {
        const size = resolveSize(m[4], model);
        if (size == null) continue;
        array = size;
      }
    } else continue;
    if (i === 0) baseType = type;
    else type = baseType; // subsequent declarators share the type
    out.push({ type, name, array });
  }
  return out;
}

function emitOne(name, fields, methods, model) {
  const L = [];
  const P = (s) => L.push(s);
  P('// <auto-generated>');
  P('using System;');
  P('using System.Numerics;');
  P('using System.Runtime.CompilerServices;');
  P('using System.Text;');
  P('');
  P('namespace Pylon.ImGui');
  P('{');
  P('    public unsafe partial struct ' + name);
  P('    {');
  for (const f of fields) {
    const mapped = f.type.includes('ImTextureRef') ? 'ImTextureRef' : csType(f.type);
    if (f.array) {
      if (LEGAL_FIXED.has(mapped)) {
        P('        public fixed ' + mapped + ' ' + f.name + '[' + f.array + '];');
      } else {
        for (let i = 0; i < f.array; i++) P('        public ' + mapped + ' ' + f.name + '_' + i + ';');
      }
    } else if (/^ImVector<.+>$/.test(f.type)) {
      P('        public ImVector ' + f.name + ';');
    } else {
      P('        public ' + mapped + ' ' + f.name + ';');
    }
  }
  P('    }');
  P('    public unsafe partial struct ' + name + 'Ptr');
  P('    {');
  P('        public ' + name + '* NativePtr { get; }');
  P('        public ' + name + 'Ptr(' + name + '* nativePtr) => NativePtr = nativePtr;');
  P('        public ' + name + 'Ptr(IntPtr nativePtr) => NativePtr = (' + name + '*)nativePtr;');
  P('        public static implicit operator ' + name + 'Ptr(' + name + '* nativePtr) => new ' + name + 'Ptr(nativePtr);');
  P('        public static implicit operator ' + name + '* (' + name + 'Ptr wrappedPtr) => wrappedPtr.NativePtr;');
  P('        public static implicit operator ' + name + 'Ptr(IntPtr nativePtr) => new ' + name + 'Ptr(nativePtr);');
  for (const f of fields) {
    const rawT = normType(f.type).replace(/\s+/g, '');
    const mapped = f.type.includes('ImTextureRef') ? 'ImTextureRef' : csType(f.type);
    const rawBool = rawT === 'bool';
    const isCstr = rawT === 'constchar*' || rawT === 'char*' || rawT === 'constchar*' || rawT === 'char*';
    if (f.array) {
      const elem = rawBool ? 'bool' : csElem(f.type);
      const startAddr = LEGAL_FIXED.has(mapped) ? ('NativePtr->' + f.name) : ('&NativePtr->' + f.name + '_0');
      P('        public RangeAccessor<' + elem + '> ' + f.name + ' => new RangeAccessor<' + elem + '>(' + startAddr + ', ' + f.array + ');');
    } else if (/^ImVector<(.+)>$/.test(f.type)) {
      const elemRaw = f.type.match(/^ImVector<(.+)>$/)[1].trim().replace(/\*\s*$/, '');
      const elem = csElem(elemRaw);
      if (PTR_WRAP[elem]) {
        P('        public ImPtrVector<' + PTR_WRAP[elem] + '> ' + f.name + ' => new ImPtrVector<' + PTR_WRAP[elem] + '>(NativePtr->' + f.name + ', Unsafe.SizeOf<' + elem + '>());');
      } else {
        P('        public ImVector<' + elem + '> ' + f.name + ' => new ImVector<' + elem + '>(NativePtr->' + f.name + ');');
      }
    } else if (mapped === 'void*' || rawT === 'void*') {
      P('        public IntPtr ' + f.name + ' { get => (IntPtr)NativePtr->' + f.name + '; set => NativePtr->' + f.name + ' = (void*)value.ToPointer(); }');
    } else if (mapped === 'IntPtr') {
      P('        public IntPtr ' + f.name + ' { get => NativePtr->' + f.name + '; set => NativePtr->' + f.name + ' = value; }');
    } else if (isCstr) {
      P('        public NullTerminatedString ' + f.name + ' => new NullTerminatedString(NativePtr->' + f.name + ');');
    } else if (mapped.endsWith('*')) {
      const base = mapped.slice(0, -1);
      if (PTR_WRAP[base]) {
        P('        public ' + PTR_WRAP[base] + ' ' + f.name + ' => new ' + PTR_WRAP[base] + '(NativePtr->' + f.name + ');');
      } else {
        P('        public ' + mapped + ' ' + f.name + ' { get => NativePtr->' + f.name + '; set => NativePtr->' + f.name + ' = value; }');
      }
    } else if (rawBool) {
      P('        public ref bool ' + f.name + ' => ref Unsafe.AsRef<bool>(&NativePtr->' + f.name + ');');
    } else {
      P('        public ref ' + mapped + ' ' + f.name + ' => ref Unsafe.AsRef<' + mapped + '>(&NativePtr->' + f.name + ');');
    }
  }
    {
    const seen = new Set();
    for (const m of methods) {
      const csParams = (m.params || []).filter(p => p.type.trim() && p.type.trim() !== '...').map(p => csType(normType(p.type)));
      const key = m.name + '|' + csParams.join(',');
      if (seen.has(key)) continue;
      seen.add(key);
      emitMethod(m, name, P);
    }
  }
  P('    }');
  P('}');
  return L.join('\n');
}

const UDT = new Set(['ImVec2','ImVec4','ImColor']);

function emitMethod(m, structName, P) {
  const params = (m.params || []).filter(p => p.type.trim() && p.type.trim() !== '...');
  const retCs = csType(m.ret);
  const rawRet = normType(m.ret);
  const returnBool = rawRet === 'bool';
  const KW = ['ref','object','event','base','in','out','params','is','as','string','int','void','byte','short','long','float','double','new','return','this','null','class','struct','enum','bool','char','uint','ushort','ulong'];
  const pnameOf = (p, i) => (p.name && !KW.includes(p.name)) ? p.name : '@' + (p.name || ('arg' + i));

  const sigParts = [];
  const prelude = [];
  const fixedOnes = [];
  const callParts = [];

  for (let i = 0; i < params.length; i++) {
    const p = params[i];
    const t = normType(p.type);
    const rawT = t.replace(/\s+/g, '');
    const name = pnameOf(p, i);
    let sigType;
    let call = name;

    if (rawT === 'bool') {
      sigType = 'bool';
      prelude.push('            byte native_' + name + ' = ' + name + ' ? (byte)1 : (byte)0;');
      call = 'native_' + name;
    } else if (rawT === 'constchar*' || rawT === 'char*') {
      sigType = 'string';
      prelude.push('            byte* native_' + name + ';');
      prelude.push('            int ' + name + '_byteCount = 0;');
      prelude.push('            if (' + name + ' != null)');
      prelude.push('            {');
      prelude.push('                ' + name + '_byteCount = Encoding.UTF8.GetByteCount(' + name + ');');
      prelude.push('                if (' + name + '_byteCount > Util.StackAllocationSizeLimit)');
      prelude.push('                {');
      prelude.push('                    native_' + name + ' = Util.Allocate(' + name + '_byteCount + 1);');
      prelude.push('                }');
      prelude.push('                else');
      prelude.push('                {');
      prelude.push('                    byte* native_' + name + '_stackBytes = stackalloc byte[' + name + '_byteCount + 1];');
      prelude.push('                    native_' + name + ' = native_' + name + '_stackBytes;');
      prelude.push('                }');
      prelude.push('                int native_' + name + '_offset = Util.GetUtf8(' + name + ', native_' + name + ', ' + name + '_byteCount);');
      prelude.push('                native_' + name + '[native_' + name + '_offset] = 0;');
      prelude.push('            }');
      prelude.push('            else { native_' + name + ' = null; }');
      call = 'native_' + name;
      m._hasStringParam = true;
    } else if (t.endsWith('&')) {
      sigType = csType(t);
      call = name;
    } else {
      const cs = csType(t);
      if (cs === 'void*' || rawT === 'void*') {
        sigType = 'IntPtr';
        call = name + '.ToPointer()';
      } else if (cs === 'byte**' || rawT === 'char**' || rawT === 'constchar**') {
        sigType = 'out byte*';
        fixedOnes.push({ cs: 'byte**', pname: name });
        call = 'native_' + name;
      } else if (cs === 'void**') {
        sigType = 'ref void*';
        fixedOnes.push({ cs: 'void**', pname: name });
        call = 'native_' + name;
      } else if (cs.endsWith('**')) {
        sigType = 'out byte*';
        fixedOnes.push({ cs: 'byte**', pname: name });
        call = 'native_' + name;
      } else if (cs.endsWith('*')) {
        const base = cs.slice(0, -1);
        if (PTR_WRAP[base]) {
          sigType = PTR_WRAP[base];
          call = name;
        } else if (['byte','int','uint','float','double','ushort','short','long','ulong','char','bool'].includes(base)) {
          const isOut = (p.name || '').toLowerCase().startsWith('out');
          sigType = (isOut ? 'out ' : 'ref ') + base;
          fixedOnes.push({ cs: base + '*', pname: name });
          call = 'native_' + name;
        } else {
          sigType = cs;
          call = name;
        }
      } else {
        sigType = cs;
        call = name;
      }
    }

    let def = '';
    if (p.hasDefault && !sigType.trim().startsWith('ref ') && !sigType.trim().startsWith('out ') && !sigType.trim().endsWith('*')) {
      const e = (p.defaultExpr || '').trim();
      let dv = null;
      if (e === 'NULL') dv = sigType === 'string' ? 'null' : ((sigType.endsWith('Ptr') || sigType === 'IntPtr') ? 'default' : '0');
      else if (e === 'true' || e === 'false') dv = e;
      else if (e === 'FLT_MAX') dv = 'float.MaxValue';
      else if (/^"([^"]*)"$/.test(e)) dv = e;
      else if (e.startsWith('ImVec2(') || e.startsWith('ImVec4(')) dv = 'default';
      else if (/^[-+0-9.eEfFuUlL]+$/.test(e)) dv = /^Im[A-Z]/.test(sigType) ? '(' + sigType + ')' + e : (sigType === 'IntPtr' ? 'default' : e);
      if (dv != null) def = ' = ' + dv;
    }
    sigParts.push({ csType: sigType.trim(), pname: name, def });
    callParts.push(call);
  }

  {
    let firstOpt = -1, dropFrom = -1;
    for (let k = 0; k < sigParts.length; k++) {
      if (sigParts[k].def) { if (firstOpt < 0) firstOpt = k; }
      else if (firstOpt >= 0) { dropFrom = firstOpt; break; }
    }
    if (dropFrom >= 0) for (let k = dropFrom; k < sigParts.length; k++) sigParts[k].def = '';
  }
  const sig = sigParts.map(s => s.csType + ' ' + s.pname + s.def).join(', ');

  let exportName = m._exportName || (structName + '_' + m.name);
  const suffixFor = () => {
    const ps = (m.params || []).filter(p => p.type.trim());
    if (!ps.length) return 'Nil';
    const t = normType(ps[0].type).replace(/\s+/g, '');
    if (t === 'constchar*') return 'Str';
    if (t === 'ImFont*') return 'FontPtr';
    if (t === 'ImVec2') return 'Vec2';
    if (t === 'ImU32') return 'U32';
    return t.replace(/[^A-Za-z0-9]/g, '') + 'Arg';
  };
  if (m._overloaded && m._ordinal > 0) exportName = structName + '_' + m.name + '_' + suffixFor();

  const selfArg = '(' + structName + '*)(NativePtr)';
  P('        public ' + (returnBool ? 'bool' : retCs) + ' ' + m.name + '(' + sig + ')');
  P('        {');
  for (const st of prelude) P(st);

  const freeStrings = () => {
    for (const p of params) {
      const name = pnameOf(p, 0);
      const t = normType(p.type).replace(/\s+/g, '');
      if (t === 'constchar*' || t === 'char*') {
        P(indent(depth) + 'if (' + name + '_byteCount > Util.StackAllocationSizeLimit)');
        P(indent(depth) + '{');
        P(indent(depth + 1) + 'Util.Free(native_' + name + ');');
        P(indent(depth) + '}');
      }
    }
  };

  const indent = (n) => ' '.repeat(12 + n * 4);
  const needsRetVar = !UDT.has(rawRet) && retCs !== 'void';
  // declare return var before fixed blocks so it stays in scope after them
  if (needsRetVar && fixedOnes.length) P(indent(0) + (returnBool ? 'byte' : retCs) + ' ret' + ((!returnBool && retCs.endsWith('*')) ? ' = null' : ' = 0') + ';');
  let depth = 0;
  for (const f of fixedOnes) {
    P(indent(depth) + 'fixed (' + f.cs + ' native_' + f.pname + ' = &' + f.pname + ')');
    P(indent(depth) + '{');
    depth++;
  }
  const callArgs = [selfArg, ...callParts].join(', ');
  if (UDT.has(rawRet)) {
    P(indent(depth) + retCs + ' __retval;');
    P(indent(depth) + 'ImGuiNative.' + exportName + '(&__retval, ' + callArgs + ');');
    freeStrings();
    P(indent(depth) + 'return __retval;');
  } else if (retCs === 'void') {
    P(indent(depth) + 'ImGuiNative.' + exportName + '(' + callArgs + ');');
    freeStrings();
  } else if (fixedOnes.length) {
    P(indent(depth) + 'ret = ImGuiNative.' + exportName + '(' + callArgs + ');');
    freeStrings();
    P(indent(depth) + 'return ' + (returnBool ? 'ret != 0' : 'ret') + ';');
  } else {
    P(indent(depth) + (returnBool ? 'byte' : retCs) + ' ret = ImGuiNative.' + exportName + '(' + callArgs + ');');
    freeStrings();
    P(indent(depth) + 'return ' + (returnBool ? 'ret != 0' : 'ret') + ';');
  }
  for (let k = 0; k < fixedOnes.length; k++) { depth--; P(indent(depth) + '}'); }
  P('        }');
}


export default { emitStructGen };