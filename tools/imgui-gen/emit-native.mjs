/**
 * Emit ImGuiNative.gen.cs — DllImport declarations, mirroring ImGui.NET.
 */
import { writeFileSync, mkdirSync } from 'fs';
import { normType, csType, PTR_WRAP } from './cs-types.mjs';

const UDT = new Set(['ImVec2','ImVec4','ImColor']);

function overloadSuffixFor(m) {
  const ps = (m.params || []).filter(p => p.type.trim());
  if (!ps.length) return 'Nil';
  const t = normType(ps[0].type).replace(/\s+/g, '');
  if (t === 'constchar*') return 'Str';
  if (t === 'ImFont*') return 'FontPtr';
  if (t === 'ImVec2') return 'Vec2';
  if (t === 'ImU32') return 'U32';
  return t.replace(/[^A-Za-z0-9]/g, '') + 'Arg';
}

export function emitNativeGen(model, outDir) {
  mkdirSync(outDir, { recursive: true });
  const sep = outDir.endsWith('/') || outDir.endsWith('\\') ? outDir : outDir + '/';
  const L = [];
  const P = (s) => L.push(s);
  P('// <auto-generated>');
  P('using System;');
  P('using System.Numerics;');
  P('using System.Runtime.InteropServices;');
  P('');
  P('namespace Pylon.ImGui');
  P('{');
  P('    public static unsafe partial class ImGuiNative');
  P('    {');
  const emitOne = (name, ret, params) => {
    P('        [DllImport("pylon", CallingConvention = CallingConvention.Cdecl)]');
    P('        public static extern ' + ret + ' ' + name + '(' + params + ');');
  };
  // free functions
  const seen = new Set();
  for (const fn of model.functions) {
    if (fn.impl) continue;
    const exportName = fn.exportName || ('ig' + fn.name);
    if (seen.has(exportName)) continue;
    seen.add(exportName);
    const rawRet = normType(fn.ret);
    const isRefRet = rawRet.endsWith('&');
    const isPtrRet = rawRet.endsWith('*');
    const baseRet = rawRet.replace(/[*&]+$/, '').trim();
    const isUdt = !isPtrRet && !isRefRet && UDT.has(baseRet);
    const ret = isUdt ? 'void'
      : (baseRet === 'void' && !isPtrRet) ? 'void'
      : (isRefRet ? csType(baseRet) + '*' : csType(rawRet));
    const pOut = isUdt ? { name: 'pOut', type: csType(baseRet) + '*' } : null;
    const params = (fn.params || []).filter(p => p.type.trim() && p.type.trim() !== '...');
    const decl = [pOut, ...params.map((p, i) => ({ name: canonical(p.name, i), type: 'void*' === csType(p.type) ? 'void*' : csType(p.type) }))]
      .filter(Boolean)
      .map(a => a.type + ' ' + a.name).join(', ');
    emitOne(exportName, ret, decl);
  }
  // member functions
  const seenM = new Set();
  for (const s of Object.values(model.structs)) {
    for (const m of (s.methods || [])) {
      if (m.name === s.name || m.name === 'operator' || m.name.startsWith('~')
        || !m.ret || m.ret === 'IMGUI_API'
        || normType(m.ret).startsWith('~') || normType(m.ret).includes('(') || normType(m.ret).includes('operator')) continue;
      if ((m.params || []).some(p => normType(p.type).includes('('))) continue;
      let exportName = s.name + '_' + m.name;
      if (m._overloaded && m._ordinal > 0) exportName = s.name + '_' + m.name + '_' + overloadSuffixFor(m);
      if (seenM.has(exportName)) continue;
      seenM.add(exportName);
      m._exportName = exportName;
      const rawRet = normType(m.ret);
      const isRefRet = rawRet.endsWith('&');
      const isPtrRet = rawRet.endsWith('*');
      const baseRet = rawRet.replace(/[*&]+$/, '').trim();
      const isUdt = !isPtrRet && !isRefRet && UDT.has(baseRet);
      const ret = isUdt ? 'void' : ((baseRet === 'void' && !isPtrRet) ? 'void' : (isRefRet ? csType(baseRet) + '*' : csType(rawRet)));
      const params = (m.params || []).filter(p => p.type.trim() && p.type.trim() !== '...');
      const pOutType = isUdt ? csType(baseRet) + '*' : null;
      // pOut first per cimgui: ImFont_CalcTextSizeA(Vector2* pOut, ImFont* self, ...)
      if (isUdt) {
        const ordered = [{ name: 'pOut', type: pOutType }, { name: 'self', type: s.name + '*' }, ...params.map((p, i) => ({ name: canonical(p.name, i), type: csType(p.type) }))];
        emitOne(exportName, 'void', ordered.map(a => a.type + ' ' + a.name).join(', '));
      } else {
        const decl = [{ name: 'self', type: s.name + '*' }, ...params.map((p, i) => ({ name: canonical(p.name, i), type: csType(p.type) }))]
          .map(a => a.type + ' ' + a.name).join(', ');
        emitOne(exportName, ret, decl);
      }
    }
  }
  P('    }');
  P('}');
  writeFileSync(sep + 'ImGuiNative.gen.cs', L.join('\n'), 'utf8');
  return L.join('\n');
}

const UDT_TYPE = { ImVec2: 'Vector2', ImVec4: 'Vector4', ImColor: 'ImColor' };

const KEYWORDS = new Set(['ref','object','event','base','params','lock','fixed','in','out','is','as','string','int','bool','float','uint','void','char','byte','short','long','double','decimal','new','return','this','null','true','false','if','else','for','foreach','while','do','switch','case','break','continue','goto','throw','try','catch','finally','default','delegate','enum','interface','namespace','operator','struct','class','const','static','public','private','protected','internal','readonly','override','virtual','sealed','abstract','using','var','async','await','where','when','yield','sizeof','typeof','stackalloc','nameof','global','partial','record']);

function canonical(name, idx) {
  if (name && !KEYWORDS.has(name)) return name;
  return '@' + (name || 'arg' + (idx + 1));
}

export default { emitNativeGen };
